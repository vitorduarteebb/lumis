SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS clients (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  person_type ENUM('F','J') NOT NULL DEFAULT 'F',
  name VARCHAR(255) NOT NULL,
  trade_name VARCHAR(255) NULL,
  document VARCHAR(20) NULL,
  state_registration VARCHAR(30) NULL,
  email VARCHAR(255) NULL,
  phone VARCHAR(30) NULL,
  mobile VARCHAR(30) NULL,
  contact_name VARCHAR(120) NULL,
  cep VARCHAR(12) NULL,
  street VARCHAR(255) NULL,
  address_number VARCHAR(30) NULL,
  complement VARCHAR(120) NULL,
  district VARCHAR(120) NULL,
  city VARCHAR(120) NULL,
  state VARCHAR(2) NULL,
  notes TEXT NULL,
  status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1=ativo,0=inativo',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NULL,
  created_by BIGINT UNSIGNED NULL,
  updated_by BIGINT UNSIGNED NULL,
  PRIMARY KEY (id),
  KEY idx_clients_company (company_id),
  KEY idx_clients_deleted (deleted_at),
  KEY idx_clients_name (name),
  KEY idx_clients_document (document),
  CONSTRAINT fk_clients_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE CASCADE,
  CONSTRAINT fk_clients_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_clients_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- Notas fiscais (gestão administrativa) + contratos — aplicar uma vez
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS fiscal_documents (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  store_id BIGINT UNSIGNED NULL,
  document_kind VARCHAR(32) NOT NULL COMMENT 'product_out,service,consumer,purchase_in',
  client_id BIGINT UNSIGNED NULL,
  supplier_id BIGINT UNSIGNED NULL,
  document_number VARCHAR(64) NULL,
  series VARCHAR(16) NULL,
  access_key VARCHAR(44) NULL,
  issued_at DATETIME NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'draft' COMMENT 'draft,issued,cancelled,voided,error',
  subtotal_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  discount_total DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  total_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  notes TEXT NULL,
  xml_path VARCHAR(512) NULL,
  pdf_path VARCHAR(512) NULL,
  purchase_order_id BIGINT UNSIGNED NULL,
  nature_entry_id BIGINT UNSIGNED NULL,
  cfop_entry_id BIGINT UNSIGNED NULL,
  model_entry_id BIGINT UNSIGNED NULL,
  series_entry_id BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NULL,
  updated_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_fd_company_kind (company_id, document_kind),
  KEY idx_fd_status (company_id, status),
  KEY idx_fd_issued (issued_at),
  KEY idx_fd_client (client_id),
  KEY idx_fd_supplier (supplier_id),
  KEY idx_fd_store (store_id),
  CONSTRAINT fk_fd_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE CASCADE,
  CONSTRAINT fk_fd_store FOREIGN KEY (store_id) REFERENCES stores (id) ON DELETE SET NULL,
  CONSTRAINT fk_fd_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE SET NULL,
  CONSTRAINT fk_fd_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


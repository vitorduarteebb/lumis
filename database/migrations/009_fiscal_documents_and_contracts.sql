CREATE TABLE IF NOT EXISTS fiscal_document_lines (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  fiscal_document_id BIGINT UNSIGNED NOT NULL,
  product_id BIGINT UNSIGNED NULL,
  service_id BIGINT UNSIGNED NULL,
  description VARCHAR(512) NULL,
  qty DECIMAL(14,4) NOT NULL DEFAULT 1.0000,
  unit_price DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  line_discount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  line_total DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  sort_order INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idx_fdl_doc (fiscal_document_id),
  CONSTRAINT fk_fdl_doc FOREIGN KEY (fiscal_document_id) REFERENCES fiscal_documents (id) ON DELETE CASCADE,
  CONSTRAINT fk_fdl_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
  CONSTRAINT fk_fdl_service FOREIGN KEY (service_id) REFERENCES services (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS contract_services (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id BIGINT UNSIGNED NOT NULL,
  store_id BIGINT UNSIGNED NULL,
  contract_number VARCHAR(64) NULL,
  client_id BIGINT UNSIGNED NOT NULL,
  service_id BIGINT UNSIGNED NULL,
  description TEXT NULL,
  start_date DATE NULL,
  end_date DATE NULL,
  amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
  adjustment_note VARCHAR(255) NULL,
  periodicity_entry_id BIGINT UNSIGNED NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'active' COMMENT 'active,suspended,closed,cancelled',
  notes TEXT NULL,
  attachment_path VARCHAR(512) NULL,
  created_by BIGINT UNSIGNED NULL,
  updated_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_cs_company (company_id),
  KEY idx_cs_client (client_id),
  KEY idx_cs_status (company_id, status),
  CONSTRAINT fk_cs_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE CASCADE,
  CONSTRAINT fk_cs_store FOREIGN KEY (store_id) REFERENCES stores (id) ON DELETE SET NULL,
  CONSTRAINT fk_cs_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE RESTRICT,
  CONSTRAINT fk_cs_service FOREIGN KEY (service_id) REFERENCES services (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

